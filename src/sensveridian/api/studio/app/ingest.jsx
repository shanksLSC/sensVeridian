const SOURCE_FPS = 30;
const SAMPLE_MODES = [
  { id: "1fps", label: "1 fps", div: 30 },
  { id: "2fps", label: "2 fps", div: 15 },
  { id: "5fps", label: "5 fps", div: 6 },
  { id: "scene", label: "scene-change", div: 42 },
  { id: "all", label: "every frame", div: 1 },
];

const USE_CASES = [
  { id: "street", label: "Automotive / Street", models: ["amod"], dataset: "street_scenes", palette: "dusk", icon: "car" },
  { id: "faces", label: "Access Control / Faces", models: ["fd", "fr"], dataset: "access_faces", palette: "indoor", icon: "face" },
  { id: "qr", label: "Warehouse / QR", models: ["qrcode"], dataset: "warehouse_qr", palette: "warehouse", icon: "qr" },
  { id: "distance", label: "Distance / Range Eval", models: ["amod", "fd", "qrcode"], dataset: "distance_eval", palette: "dusk", icon: "ruler" },
];

const SAMPLE_VIDEOS = [
  { name: "ring_cam_driveway_0412.mp4", dur: 184, w: 1920, h: 1080, size: 248, palette: "dusk", uc: "street" },
  { name: "lobby_entrance_am.mov", dur: 96, w: 1280, h: 720, size: 121, palette: "indoor", uc: "faces" },
  { name: "forklift_aisle22.mp4", dur: 312, w: 2560, h: 1440, size: 512, palette: "warehouse", uc: "qr" },
  { name: "hwy_onramp_dashcam.mp4", dur: 240, w: 1920, h: 1080, size: 380, palette: "dusk", uc: "street" },
  { name: "range_test_5to30ft.mp4", dur: 150, w: 1920, h: 1080, size: 210, palette: "dusk", uc: "distance" },
];

function fmtDur(s) { const m = Math.floor(s / 60); return m + ":" + String(Math.round(s % 60)).padStart(2, "0"); }
function estFrames(dur, modeId) { const m = SAMPLE_MODES.find((x) => x.id === modeId); return Math.max(1, Math.round((dur * SOURCE_FPS) / m.div)); }
function posterFor(palette, seed) {
  const d = window.VD.datasets.find((x) => x.palette === palette && x.kind === "vision") || window.VD.datasets[0];
  return d.images[seed % d.images.length];
}
function resolveDsName(uc) {
  if (!uc) return "";
  if (uc.dataset) return window.VD.getDataset(uc.dataset)?.name || uc.datasetName || uc.label;
  return uc.datasetName || uc.label;
}
function ucColor(uc) { return vhelp.modelColor(uc.models[0] === "fd" ? "fd" : uc.models[0]); }

let _vid = 0;
function makeVideo(spec) {
  return {
    key: "v" + (++_vid), name: spec.name, dur: spec.dur, w: spec.w, h: spec.h, size: spec.size,
    palette: spec.palette || "dusk", uc: spec.uc || null, mode: "2fps", url: spec.url || null,
    poster: posterFor(spec.palette || "dusk", _vid),
  };
}

