/* ============================ VIDEO AUTO-LABEL FLOW ====================== */
function VideoIngestFlow({ onExit }) {
  const ctx = React.useContext(VDCtx);
  const { t, setTweak } = ctx;
  const [stage, setStage] = React.useState("compose");
  const [videos, setVideos] = React.useState(() => SAMPLE_VIDEOS.slice(0, 3).map(makeVideo));
  const [customCases, setCustomCases] = React.useState([]);
  const [addTagFor, setAddTagFor] = React.useState(null);
  const fileRef = React.useRef(null);
  const useCases = React.useMemo(() => [...USE_CASES, ...customCases], [customCases]);

  const addSamples = () => setVideos((v) => { const ex = new Set(v.map((x) => x.name)); const next = SAMPLE_VIDEOS.filter((s) => !ex.has(s.name)).map(makeVideo); return next.length ? [...v, ...next] : v; });
  const onFiles = (e) => {
    const files = [...(e.target.files || [])];
    const added = files.map((f) => {
      const url = URL.createObjectURL(f);
      const v = makeVideo({ name: f.name, dur: 120, w: 1920, h: 1080, size: Math.round(f.size / 1048576), palette: "dusk", url });
      const probe = document.createElement("video"); probe.preload = "metadata"; probe.src = url;
      probe.onloadedmetadata = () => setVideos((vs) => vs.map((x) => x.key === v.key ? { ...x, dur: probe.duration || 120, w: probe.videoWidth || x.w, h: probe.videoHeight || x.h } : x));
      return v;
    });
    setVideos((v) => [...v, ...added]); e.target.value = "";
  };
  const update = (key, patch) => setVideos((v) => v.map((x) => x.key === key ? { ...x, ...patch } : x));
  const remove = (key) => setVideos((v) => v.filter((x) => x.key !== key));
  const setAllMode = (mode) => setVideos((v) => v.map((x) => ({ ...x, mode })));

  const createCustomCase = (data) => {
    let base = data.label.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "").slice(0, 24) || "tag";
    let id = base, i = 2; while (useCases.some((u) => u.id === id)) id = base + "_" + i++;
    const palette = data.models.includes("amod") ? "dusk" : (data.models.includes("fd") || data.models.includes("fr")) ? "indoor" : data.models.includes("qrcode") ? "warehouse" : "dusk";
    const uc = { id, label: data.label, models: data.models, dataset: null, datasetName: data.label, palette, icon: data.icon, isNew: true };
    setCustomCases((c) => [...c, uc]);
    if (addTagFor && addTagFor !== "__global") update(addTagFor, { uc: id, palette, poster: posterFor(palette, id.length + 3) });
    setAddTagFor(null);
  };

  const finishIngest = () => {
    const updated = customCases.map((uc) => {
      if (uc.isNew && !uc.created) {
        const grp = videos.filter((v) => v.uc === uc.id);
        if (grp.length) {
          const frames = grp.reduce((s, v) => s + estFrames(v.dur, v.mode), 0);
          const n = Math.min(40, Math.max(10, Math.round(frames / 600)));
          const ds = window.VD.createDataset({ name: uc.label, desc: `Ingested via the “${uc.label}” use-case tag.`, models: uc.models, palette: uc.palette, n });
          return { ...uc, dataset: ds.id, created: true };
        }
      }
      return uc;
    });
    setCustomCases(updated); setStage("done");
    // record the ingest job through the backend seam (server does the real
    // frame-split + inference; the mock just acknowledges it)
    try {
      window.VeridianAPI && window.VeridianAPI.createIngestJob({
        source: "video",
        trustThreshold: t.autoAccept ? t.trustThreshold : null,
        groups: groups.map((g) => ({ tag: g.uc.id, label: g.uc.label, models: g.uc.models, videos: g.vs.length, frames: g.frames, dataset: g.uc.dataset, isNew: !!g.uc.isNew })),
      });
    } catch (e) { /* offline */ }
  };

  const tagged = videos.filter((v) => v.uc);
  const untagged = videos.length - tagged.length;
  const totalFrames = tagged.reduce((s, v) => s + estFrames(v.dur, v.mode), 0);
  const groups = useCases.map((uc) => { const vs = videos.filter((v) => v.uc === uc.id); return { uc, vs, frames: vs.reduce((s, v) => s + estFrames(v.dur, v.mode), 0) }; }).filter((g) => g.vs.length);

  if (stage === "processing") {
    const allModels = [...new Set(groups.flatMap((g) => g.uc.models))];
    const log = [
      "» connecting to veridian-db.lattice.internal (PostgreSQL)",
      ...groups.flatMap((g) => g.vs.map((v) => `» queued ${v.name}  →  #${g.uc.id}`)),
      "» ffmpeg decode: " + groups.reduce((s, g) => s + g.vs.length, 0) + " streams",
      "» sampling frames at configured rates",
      "» loading oracle weights: " + allModels.join(", "),
      "» running inference on sampled frames",
      t.autoAccept ? `» auto-accepting detections ≥ ${t.trustThreshold.toFixed(2)} with model consensus` : "» all detections queued for review",
      "» sha-256 content hashing + dedup",
      "» upserting predictions_summary + predictions_raw",
      "✓ ingest complete",
    ];
    return <ProcessingView title="sensVeridian is processing your videos" subtitle="Splitting into frames, auto-labelling, and combining per tag."
      stages={[{ label: "Decoding", icon: "film" }, { label: "Sampling frames", icon: "image" }, { label: "Auto-labelling", icon: "cpu" }, { label: "Hash + dedup", icon: "link" }, { label: "Writing to Postgres", icon: "database" }]}
      models={allModels} modelStage={2} total={totalFrames} unit="frames" logLines={log} onDone={finishIngest} />;
  }
  if (stage === "done") {
    const cards = groups.map((g) => {
      const autoAcc = t.autoAccept ? Math.round(g.frames * 0.6) : 0;
      const conflicts = Math.round(g.frames * 0.11);
      return {
        icon: g.uc.icon, color: ucColor(g.uc), title: resolveDsName(g.uc), badge: g.uc.isNew ? "created" : null,
        sub: `${g.vs.length} video${g.vs.length !== 1 ? "s" : ""} · ${g.uc.label}`,
        stats: [{ v: "+" + g.frames.toLocaleString(), l: "frames", c: "var(--match)" }, ...(autoAcc ? [{ v: autoAcc.toLocaleString(), l: "auto-accepted", c: "var(--pred)" }] : []), { v: conflicts.toLocaleString(), l: "to review", c: "var(--gt)" }],
        openDsId: g.uc.dataset,
      };
    });
    return <DoneView title="Ingest complete" subtitle={`${totalFrames.toLocaleString()} frames split, auto-labelled, and committed across ${groups.length} dataset${groups.length !== 1 ? "s" : ""}.`}
      cards={cards} onReset={() => { setVideos([]); setStage("compose"); }} onExit={onExit} go={ctx.go} />;
  }

  return (
    <>
      <TopBar crumbs={[{ label: "New source", onClick: onExit }, { label: "Auto-label video" }]}>
        <span style={{ fontSize: 12, color: "var(--tx-2)" }}>{videos.length} video{videos.length !== 1 ? "s" : ""} · {tagged.length} tagged</span>
        <button className="btn" onClick={() => fileRef.current.click()}><Icon name="upload" size={15} />Add files</button>
        <input ref={fileRef} type="file" accept="video/*" multiple style={{ display: "none" }} onChange={onFiles} />
        <button className="btn primary" disabled={!tagged.length} onClick={() => setStage("processing")} style={{ opacity: tagged.length ? 1 : 0.45, cursor: tagged.length ? "pointer" : "not-allowed" }}><Icon name="sparkle" size={15} />Send to sensVeridian</button>
      </TopBar>
      <div style={{ flex: 1, display: "flex", minHeight: 0 }}>
        <div className="scroll" style={{ flex: 1, padding: "20px 24px" }}>
          <div style={{ maxWidth: 820, margin: "0 auto" }}>
            {videos.length === 0 ? <DropZone onBrowse={() => fileRef.current.click()} onSamples={addSamples} big label="Drop video files to ingest" sample="load sample clips" /> : (
              <>
                <div style={{ display: "flex", alignItems: "center", gap: 12, marginBottom: 14 }}>
                  <div style={{ fontSize: 12, fontWeight: 600, color: "var(--tx-2)", textTransform: "uppercase", letterSpacing: ".06em" }}>Source videos</div>
                  <div style={{ flex: 1 }} />
                  <span style={{ fontSize: 11.5, color: "var(--tx-2)" }}>Sample all at</span>
                  <div style={{ display: "flex", gap: 4 }}>{SAMPLE_MODES.slice(0, 4).map((m) => <button key={m.id} className="btn sm" onClick={() => setAllMode(m.id)} style={{ padding: "4px 9px", color: "var(--tx-1)" }}>{m.label}</button>)}</div>
                </div>
                <div style={{ display: "flex", flexDirection: "column", gap: 10 }}>{videos.map((v) => <VideoRow key={v.key} v={v} useCases={useCases} update={update} remove={remove} onAddTag={() => setAddTagFor(v.key)} />)}</div>
                <DropZone onBrowse={() => fileRef.current.click()} onSamples={addSamples} label="Drop more videos" sample="samples" />
              </>
            )}
          </div>
        </div>
        <PlanPanel groups={groups} untagged={untagged} totalFrames={totalFrames} onStart={() => setStage("processing")} onAddTag={() => setAddTagFor("__global")} t={t} setTweak={setTweak} />
      </div>
      {addTagFor !== null && <AddTagModal existing={useCases} onClose={() => setAddTagFor(null)} onCreate={createCustomCase} />}
    </>
  );
}

function DropZone({ onBrowse, onSamples, big, label, sample }) {
  const [over, setOver] = React.useState(false);
  return (
    <div onClick={onBrowse} onDragOver={(e) => { e.preventDefault(); setOver(true); }} onDragLeave={() => setOver(false)} onDrop={(e) => { e.preventDefault(); setOver(false); onSamples && onSamples(); }}
      style={{ border: "1.5px dashed " + (over ? "var(--accent)" : "var(--line-2)"), background: over ? "var(--accent-dim)" : "var(--bg-1)", borderRadius: 12, padding: big ? "56px 24px" : "22px 24px", textAlign: "center", cursor: "pointer", marginTop: big ? 0 : 14, transition: "border-color .12s, background .12s" }}>
      <div style={{ width: big ? 56 : 40, height: big ? 56 : 40, margin: "0 auto", borderRadius: 14, background: "var(--bg-3)", border: "1px solid var(--line-2)", display: "grid", placeItems: "center", color: "var(--accent-2)" }}><Icon name="upload" size={big ? 26 : 20} /></div>
      <div style={{ fontSize: big ? 16 : 13.5, fontWeight: 600, marginTop: big ? 16 : 10 }}>{label || "Drop files"}</div>
      <div style={{ fontSize: 12, color: "var(--tx-2)", marginTop: 4 }}>or <button onClick={(e) => { e.stopPropagation(); onBrowse(); }} style={{ color: "var(--accent-2)", fontWeight: 600 }}>browse</button>{sample && onSamples && <> · <button onClick={(e) => { e.stopPropagation(); onSamples(); }} style={{ color: "var(--accent-2)", fontWeight: 600 }}>{sample}</button></>}</div>
    </div>
  );
}

