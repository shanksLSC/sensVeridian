/* live, WS-driven progress (real ingest job, not a timer simulation) */
function LiveProcessing({ job, onDone }) {
  const STAGE_ICONS = { "Decoding": "film", "Sampling frames": "image", "Auto-labelling": "cpu", "Hash + dedup": "link", "Writing to Postgres": "database" };
  const STAGE_ORDER = ["Decoding", "Sampling frames", "Auto-labelling", "Hash + dedup", "Writing to Postgres"];
  const [frame, setFrame] = React.useState({ stage: "Queued", progress: 0, framesDone: 0, framesTotal: 0, status: "queued" });
  const [log, setLog] = React.useState(["» job " + job.jobId + " queued"]);
  const logRef = React.useRef(null);
  const doneRef = React.useRef(false);

  React.useEffect(() => {
    const unsub = window.VeridianAPI.subscribeJob(job.jobId, (f) => {
      setFrame(f);
      setLog((l) => [...l.slice(-60), `» ${f.stage}  ${f.framesDone || 0}/${f.framesTotal || 0}${f.status === "error" ? "  ERROR: " + (f.error || "") : ""}`]);
      if ((f.status === "done" || f.status === "error") && !doneRef.current) {
        doneRef.current = true;
        Promise.all((job.groups || []).map((g) => (window.VD.ensureDataset ? window.VD.ensureDataset(g.dataset).catch(() => {}) : Promise.resolve())))
          .then(() => setTimeout(onDone, 600));
      }
    });
    return () => { try { unsub && unsub(); } catch (e) { /* noop */ } };
  }, []);
  React.useEffect(() => { if (logRef.current) logRef.current.scrollTop = logRef.current.scrollHeight; }, [log]);

  const curStage = Math.max(0, STAGE_ORDER.indexOf(frame.stage));
  return (
    <>
      <TopBar crumbs={[{ label: "New source" }, { label: "Processing" }]} />
      <div style={{ flex: 1, display: "grid", placeItems: "center", padding: 24, overflow: "auto" }}>
        <div style={{ width: 720, maxWidth: "100%" }}>
          <div style={{ textAlign: "center", marginBottom: 26 }}>
            <div style={{ fontSize: 19, fontWeight: 700 }}>sensVeridian is running the models</div>
            <div style={{ fontSize: 13, color: "var(--tx-2)", marginTop: 4 }}>Live progress from the ingest worker over the WebSocket.</div>
          </div>
          <div style={{ display: "flex", alignItems: "center", marginBottom: 24 }}>
            {STAGE_ORDER.map((s, i) => (
              <React.Fragment key={s}>
                <div style={{ display: "flex", flexDirection: "column", alignItems: "center", gap: 7 }}>
                  <div style={{ width: 40, height: 40, borderRadius: "50%", display: "grid", placeItems: "center", border: "2px solid " + (i < curStage ? "var(--match)" : i === curStage ? "var(--accent)" : "var(--line-2)"), background: i < curStage ? "var(--match-soft)" : i === curStage ? "var(--accent-dim)" : "var(--bg-1)", color: i < curStage ? "var(--match)" : i === curStage ? "var(--accent-2)" : "var(--tx-3)" }}>{i < curStage ? <Icon name="check" size={18} /> : <Icon name={STAGE_ICONS[s]} size={17} />}</div>
                  <span style={{ fontSize: 10.5, color: i <= curStage ? "var(--tx-1)" : "var(--tx-3)", whiteSpace: "nowrap", fontWeight: i === curStage ? 600 : 400 }}>{s}</span>
                </div>
                {i < STAGE_ORDER.length - 1 && <div style={{ flex: 1, height: 2, background: i < curStage ? "var(--match)" : "var(--line-2)", margin: "0 4px", marginBottom: 22 }} />}
              </React.Fragment>
            ))}
          </div>
          <div className="card" style={{ padding: 16, marginBottom: 14 }}>
            <div style={{ display: "flex", justifyContent: "space-between", marginBottom: 8, fontSize: 12.5 }}>
              <span style={{ fontWeight: 600 }}>{frame.stage}…</span>
              <span className="mono tnum" style={{ color: "var(--accent-2)" }}>{(frame.framesDone || 0).toLocaleString()} / {(frame.framesTotal || 0).toLocaleString()} frames</span>
            </div>
            <div className="meter" style={{ height: 8 }}><i style={{ width: (frame.progress || 0) + "%", background: frame.status === "error" ? "var(--conflict)" : "linear-gradient(90deg,var(--accent),var(--accent-2))", transition: "width .2s" }} /></div>
          </div>
          <div ref={logRef} className="card scroll" style={{ height: 170, padding: "10px 14px", fontFamily: "var(--mono)", fontSize: 11.5, lineHeight: 1.7, background: "var(--bg-canvas)" }}>
            {log.map((l, i) => <div key={i} style={{ color: l.includes("ERROR") ? "var(--conflict)" : "var(--tx-1)" }}>{l}</div>)}
            {frame.status !== "done" && frame.status !== "error" && <span style={{ color: "var(--accent-2)" }}>▌</span>}
          </div>
        </div>
      </div>
    </>
  );
}

