            <select value={v.mode} onChange={(e) => update(v.key, { mode: e.target.value })} style={{ background: "var(--bg-3)", border: "1px solid var(--line-2)", borderRadius: 6, color: "var(--tx-0)", padding: "4px 7px", fontSize: 11.5 }}>{SAMPLE_MODES.map((m) => <option key={m.id} value={m.id}>{m.label}</option>)}</select>
